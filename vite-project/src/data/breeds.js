export function getBreedName(breed, t) {
  if (!breed) return '';
  const breedId = typeof breed === 'string' ? breed : breed.id;
  const originalName = typeof breed === 'object' ? breed.name : breed;
  
  if (t && breedId) {
    const translated = t(`breeds.${breedId}`);
    if (translated && translated !== `breeds.${breedId}`) {
      return translated;
    }
  }
  return originalName || '';
}
